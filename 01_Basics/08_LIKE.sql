-- ============================================================================
-- Sample Data
-- ============================================================================

SELECT *
FROM Customers;

-- ============================================================================
-- 1. Names Starting with 'S'
-- ============================================================================

SELECT *
FROM Customers
WHERE FirstName LIKE 'S%';

-- ============================================================================
-- 2. Names Ending with 'S'
-- ============================================================================

SELECT *
FROM Customers
WHERE FirstName LIKE '%S';

-- ============================================================================
-- 3. Names Containing 'an'
-- ============================================================================

SELECT *
FROM Customers
WHERE FirstName LIKE '%an%';

-- ============================================================================
-- 4. Second Character is 'a'
-- ============================================================================

SELECT *
FROM Customers
WHERE FirstName LIKE '_a%';

-- ============================================================================
-- 5. Names with Exactly 5 Characters
-- ============================================================================

SELECT *
FROM Customers
WHERE FirstName LIKE '_____';

-- ============================================================================
-- 6. Names Starting with 'A' and Ending with 'n'
-- ============================================================================

SELECT *
FROM Customers
WHERE FirstName LIKE 'A%n';

-- ============================================================================
-- 7. Email Ending with '.com'
-- ============================================================================

SELECT *
FROM Customers
WHERE Email LIKE '%.com';

-- ============================================================================
-- Notes
-- ============================================================================
-- %  : Matches zero or more characters.
-- _  : Matches exactly one character.
--
-- Examples:
-- 'S%'     -> Starts with S
-- '%S'     -> Ends with S
-- '%an%'   -> Contains "an"
-- '_a%'    -> Second character is 'a'
-- '_____'  -> Exactly 5 characters